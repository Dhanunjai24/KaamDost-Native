let currentLangCode = 'en';

export const setLanguage = (lang) => {
  if (TRANSLATIONS[lang]) {
    currentLangCode = lang;
    try {
      AsyncStorage.setItem('@kaamdost_language', lang).catch(() => {});
    } catch (e) {}
  }
};

export const initLanguage = async () => {
  try {
    const saved = await AsyncStorage.getItem('@kaamdost_language');
    if (saved && TRANSLATIONS[saved]) {
      currentLangCode = saved;
      return saved;
    }
  } catch (e) {}
  return currentLangCode;
};

export const getLanguage = () => currentLangCode;

export const t = (key) => {
  const dict = TRANSLATIONS[currentLangCode] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
};
